export function installSchedulerLocale(ctx: SchedulerClientContext): void {
  ctx.effect(() => [
    ctx.locale.register(LOCALE_NAMESPACE, 'zh', zh),
    ctx.locale.register(LOCALE_NAMESPACE, 'en', en),
  ], `${PLUGIN_ID}: locale`)
}
